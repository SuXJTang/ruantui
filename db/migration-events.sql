-- ============================================================
-- migration-events.sql — v4.0.0「灯塔」M1 数据地基
-- 目的：新增 event 事件表 + 去重写入函数，用于时间序列/转化漏斗分析。
--
-- 与现有 tools.views / tools.downloads 的关系：
--   · views / downloads  → 页面展示用的「累计值」，继续由 increment_tool_* 维护
--   · events             → 只追加的明细，用于看板「趋势 / 漏斗」
--   两者记录同一动作但用途不同，看板不要把二者相加。
--
-- 安全：不给 anon/authenticated 表级 insert，写入只能走 security definer
--       的 record_event()，避免任人往表里灌数据。
-- ============================================================

create table if not exists public.events (
    id           bigint generated by default as identity primary key,
    event_name   text not null check (event_name in (
        'tool_view','tool_download','tool_favorite','tool_unfavorite',
        'user_register','vip_activated')),
    actor_type   text not null check (actor_type in ('anon','user')),
    user_id      uuid references auth.users(id) on delete set null,
    anon_session text,
    tool_id      bigint references public.tools(id) on delete cascade,
    context      jsonb default '{}'::jsonb,
    created_at   timestamptz not null default now()
);

create index if not exists events_name_created_idx on public.events (event_name, created_at desc);
create index if not exists events_tool_id_idx on public.events (tool_id) where tool_id is not null;
create index if not exists events_user_id_idx on public.events (user_id) where user_id is not null;
create index if not exists events_created_idx on public.events (created_at desc);

alter table public.events enable row level security;

-- 不开放表级写入；只允许通过 record_event() 写入
revoke insert on public.events from anon, authenticated;

-- 管理员可读全量（复用已有 is_admin()）
drop policy if exists "events_admin_read" on public.events;
create policy "events_admin_read" on public.events
    for select using (public.is_admin());

-- 登录用户可读自己的事件
drop policy if exists "events_user_read_own" on public.events;
create policy "events_user_read_own" on public.events
    for select using (user_id = auth.uid());

-- 去重写入：同一 actor 对同一工具的同类事件，10 秒内只记一次
create or replace function public.record_event(
    p_event_name text,
    p_tool_id bigint default null,
    p_context jsonb default '{}'::jsonb,
    p_anon_session text default ''
) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_uid   uuid := auth.uid();
    v_actor text := case when auth.uid() is null then 'anon' else 'user' end;
    v_dup   boolean;
begin
    select exists(
        select 1 from public.events
         where event_name = p_event_name
           and coalesce(tool_id, -1) = coalesce(p_tool_id, -1)
           and ( (v_uid is not null and user_id = v_uid)
              or (v_uid is null and user_id is null and anon_session = p_anon_session) )
           and created_at > now() - interval '10 seconds'
    ) into v_dup;
    if v_dup then return; end if;

    insert into public.events (event_name, actor_type, user_id, anon_session, tool_id, context)
    values (p_event_name, v_actor, v_uid,
            case when v_uid is null then p_anon_session else null end,
            p_tool_id, coalesce(p_context, '{}'::jsonb));
end; $$;

comment on function public.record_event(text,bigint,jsonb,text) is
    'v4 灯塔：记录用户行为事件，10 秒内同 actor 同工具同类事件去重';

revoke all on function public.record_event(text,bigint,jsonb,text) from public;
grant execute on function public.record_event(text,bigint,jsonb,text) to anon, authenticated;

